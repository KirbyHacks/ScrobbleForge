def album_run(name):
    return {"text": name, "navigationEndpoint": {"browseEndpoint": {
        "browseEndpointContextSupportedConfigs": {"browseEndpointContextMusicConfig": {
            "pageType": "MUSIC_PAGE_TYPE_ALBUM"}}}}}


@pytest.mark.parametrize("runs,expected", [
    ([{"text": "3:00"}], None), ([{"text": "1M views"}], None),
    ([{"text": "2024"}], None), ([{"text": "Album"}], None),
    ([album_run("Live Album")], "Live Album"),
])
def test_subtitle_and_third_column_require_album_link(runs, expected):
    def col(items):
        return {"musicResponsiveListItemFlexColumnRenderer": {"text": {"runs": items}}}
    for third_column in (False, True):
        columns = [col([{"text": "Song (Live)"}]), col([{"text": "Artist"}])]
        if third_column:
            columns.append(col(runs))
        else:
            columns[1] = col([{"text": "Artist"}, {"text": " • "}] + runs)
        renderer = {"playlistItemData": {"videoId": "video"}, "flexColumns": columns,
                    "fixedColumns": [{"musicResponsiveListItemFixedColumnRenderer": {
                        "text": {"runs": [{"text": "3:00"}]}}}]}
        track = YouTubeAdapter()._parse_youtubei_item_renderer(renderer, "https://youtube.com/playlist?list=test")
        assert track.album == expected
        assert track.duration_ms == 180000


@pytest.mark.parametrize("provider", ["spotify", "youtube_player", "youtube_api", "youtube_playlist"])
def test_provider_metadata_reaches_now_playing_and_scrobble(provider):
    session = MagicMock()
    snippet = {"title": "Song (Live)", "channelTitle": "Artist - Topic", "description": DESCRIPTION}
    if provider == "spotify":
        canonical = SpotifyAdapter.map_to_canonical({
            "name": "Song (Live)", "artists": [{"name": "Artist"}],
            "album": {"name": "Live Album", "artists": [{"name": "Album Artist"}]},
            "duration_ms": 180000, "track_number": 4,
        })
    elif provider == "youtube_player":
        session.post.return_value.json.return_value = {"videoDetails": {
            "title": snippet["title"], "author": snippet["channelTitle"],
            "shortDescription": DESCRIPTION, "lengthSeconds": "180"}}
        canonical = YouTubeAdapter(session=session).fetch_sources(["https://youtube.com/watch?v=video"])[0]
    elif provider == "youtube_api":
        session.get.return_value.json.return_value = {"items": [{"id": "video", "snippet": snippet,
                                                                "contentDetails": {"duration": "PT3M"}}]}
        canonical = YouTubeAdapter(api_key="test-key", session=session).fetch_sources(["https://youtube.com/watch?v=video"])[0]
    else:
        playlist_response, video_response = MagicMock(), MagicMock()
        playlist_response.json.return_value = {"items": [{"snippet": {
            "title": snippet["title"], "videoOwnerChannelTitle": "Artist - Topic",
            "resourceId": {"videoId": "video"}, "description": "not the release metadata"}}]}
        video_response.json.return_value = {"items": [{"id": "video", "snippet": snippet,
                                                       "contentDetails": {"duration": "PT3M"}}]}
        session.get.side_effect = [playlist_response, video_response]
        canonical = YouTubeAdapter(api_key="test-key", session=session).fetch_sources(["https://youtube.com/playlist?list=test"])[0]
    track = to_legacy_track(canonical)
    assert (track.artist, track.title, track.album) == ("Artist", "Song (Live)", "Live Album")
    client = LastFMClient.__new__(LastFMClient)
    client.network = MagicMock()
    assert client.update_now_playing(track)
    params = client.network.update_now_playing.call_args.kwargs
    assert (params["artist"], params["title"], params["album"]) == (track.artist, track.title, track.album)
    assert params["album_artist"] == ("Album Artist" if provider == "spotify" else "Artist")
    assert params["track_number"] == (4 if provider == "spotify" else None)
    response = minidom.parseString('<lfm><scrobbles accepted="1" ignored="0"><scrobble><ignoredMessage code="0"/></scrobble></scrobbles></lfm>')
    with patch("src.lastfm_client.pylast._Request") as request:
        request.return_value.execute.return_value = response
        assert client.scrobble(track, timestamp=1000)
    submitted = request.call_args.args[2]
    assert submitted["artist[0]"] == params["artist"]
    assert submitted["track[0]"] == params["title"]
    assert submitted["album[0]"] == params["album"]
    assert submitted["albumArtist[0]"] == params["album_artist"]


SPOTIFY_ID = "1jux3g1YXNub0NkYbLTLIp"


def public_track_page(track=None, recommendations=None):
    if track is None:
        track = {"__typename": "Track", "uri": f"spotify:track:{SPOTIFY_ID}",
                 "name": "Song (Live)", "firstArtist": {"items": [{"profile": {"name": "Artist"}}]},
                 "albumOfTrack": {"name": "Live Album", "uri": "spotify:album:4itKk52E9ZCdWUQcFAkud9"},
                 "trackNumber": 4}
    payload = {"entities": {"items": {f"spotify:track:{SPOTIFY_ID}": track}},
               "internalLinkRecommender": recommendations or {}}
    return '<script id="initialState" type="text/plain">' + base64.b64encode(json.dumps(payload).encode()).decode() + '</script>'


def sparse_spotify_track():
    return Track("Song (Live)", "Artist", spotify_id=SPOTIFY_ID, provider_id="spotify")


def test_sparse_playlist_album_resolved_before_lastfm_submission():
    engine = make_engine()
    engine.source_service = SourceIngestionService(spotify_client=SpotifyClient())
    track = sparse_spotify_track()
    engine.queue.get_next_track.side_effect = [track, None]
    response = MagicMock(status_code=200, text=public_track_page())
    sent = []
    engine.lastfm.update_now_playing.side_effect = lambda t: sent.append((t.artist, t.title, t.album, t.track_number))
    engine.lastfm.scrobble.side_effect = lambda t, timestamp: sent.append((t.artist, t.title, t.album, t.track_number)) or True
    with patch("src.spotify_client.requests.get", return_value=response), patch.object(engine.stop_event, "wait", return_value=False):
        engine.run()
    assert sent == [("Artist", "Song (Live)", "Live Album", 4)] * 2


def test_album_lookup_cache_preserves_duplicates_and_source_metadata():
    client = SpotifyClient()
    first, duplicate = sparse_spotify_track(), sparse_spotify_track()
    with patch("src.spotify_client.requests.get", return_value=MagicMock(status_code=200, text=public_track_page())) as get:
        client.enrich_track_metadata(first)
        client.enrich_track_metadata(duplicate)
    get.assert_called_once()
    assert "Mobile" in get.call_args.kwargs["headers"]["User-Agent"]
    assert first.album == duplicate.album == "Live Album"
    assert (first.title, first.artist, first.spotify_id) == ("Song (Live)", "Artist", SPOTIFY_ID)


@pytest.mark.parametrize("field,value", [
    ("name", "Song"), ("uri", "spotify:track:other"), ("__typename", "Episode"),
    ("albumOfTrack", None), ("albumOfTrack", {"name": "Album", "uri": "spotify:artist:someone"}),
    ("firstArtist", {"items": [{"profile": {"name": "Other artist"}}]}),
])
def test_album_lookup_rejects_mismatched_identity(field, value):
    page = public_track_page()
    item = json.loads(base64.b64decode(page.split('>')[1].split('<')[0]))["entities"]["items"][f"spotify:track:{SPOTIFY_ID}"]
    item[field] = value
    assert SpotifyClient._track_page_metadata(public_track_page(item), sparse_spotify_track()) is None


def test_album_lookup_does_not_read_recommended_albums():
    page = public_track_page(track={}, recommendations={"similarAlbums": [{"name": "Wrong Album"}]})
    assert SpotifyClient._track_page_metadata(page, sparse_spotify_track()) is None


