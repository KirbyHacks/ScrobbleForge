def make_engine(mode="realistic", enabled=True):
    tracker = MagicMock()
    tracker.get_state.return_value = None
    tracker.can_scrobble.return_value = (True, 0)
    tracker.get_rolling_24h_count.return_value = 1
    queue = MagicMock()
    queue.get_next_track.side_effect = [Track("Song", "Artist", duration_ms=180000), None]
    cfg = AppConfig(lastfm=LastFMConfig(api_key="key", api_secret="secret"), spotify=SpotifyConfig(),
                    engine=EngineConfig(mode=mode, update_now_playing=enabled))
    return ScrobblerEngine(cfg, MagicMock(), queue=queue, tracker=tracker, stop_event=threading.Event())


def test_retry_preserves_start_without_reannouncing_or_replaying():
    engine = make_engine()
    engine.lastfm.scrobble.side_effect = [LastFMTemporaryError("offline"), True]
    with patch.object(engine.stop_event, "wait", return_value=False) as wait, patch(
        "src.engine.time.time", side_effect=range(1000, 1100)
    ), patch("src.engine.time.monotonic", side_effect=[100, 195]):
        engine.run()
    calls = engine.lastfm.scrobble.call_args_list
    assert len(calls) == 2
    assert calls[0] == calls[1]
    engine.lastfm.update_now_playing.assert_called_once()
    engine.queue.commit_track_progress.assert_called_once()
    assert [c.kwargs["timeout"] for c in wait.call_args_list][:2] == [90, 10]
    assert len(wait.call_args_list) == 3  # playback, retry wait and pause


def test_quota_wait_does_not_announce_playback():
    engine = make_engine()
    engine.tracker.can_scrobble.return_value = (False, 300)
    def stop(timeout):
        engine.stop_event.set()
        return True
    with patch.object(engine.stop_event, "wait", side_effect=stop):
        engine.run()
    engine.lastfm.update_now_playing.assert_not_called()
    engine.lastfm.scrobble.assert_not_called()


