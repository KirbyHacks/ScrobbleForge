def test_album_lookup_rate_limit_cools_down_for_other_tracks():
    client = SpotifyClient()
    response = MagicMock(status_code=429)
    response.raise_for_status.side_effect = requests.HTTPError("rate limited")
    track, other = sparse_spotify_track(), sparse_spotify_track()
    other.spotify_id = "6zJ68ym0Buv2TpuUu8tw9A"
    with patch("src.spotify_client.requests.get", return_value=response) as get:
        client.enrich_track_metadata(track)
        client.enrich_track_metadata(other)
    get.assert_called_once()
    assert track.album == other.album == ""


